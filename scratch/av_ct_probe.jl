function rinterp(row, tsr)
    tsr <= TSRK[1] && return row[1]
    tsr >= TSRK[end] && return row[end]
    for j in 1:(length(TSRK) - 1)
        if TSRK[j] <= tsr <= TSRK[j + 1]
            t = (tsr - TSRK[j]) / (TSRK[j + 1] - TSRK[j])
            return row[j] + t * (row[j + 1] - row[j])
        end
    end
    return row[end]
end

