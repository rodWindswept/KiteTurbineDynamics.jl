    rct = rinterp(RATIO_CT[n - 2], lam)
    rcp = rinterp(RATIO_CP[n - 2], lam)
    println("n=", n, "  Rf_CT=", round(rct, digits=6),
            "  ct_at_tsr*Rf_CT=", round(ct3 * rct, digits=4),
            "  Rf_CP=", round(rcp, digits=6),
            "  cp_at_tsr*Rf_CP=", round(cp3 * rcp, digits=4))
end
